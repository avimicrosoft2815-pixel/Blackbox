"""The 60-secret corpus, with the rule that makes it a test rather than a demo.

Every secret here is synthetic and generated by `_make` from a label — nothing in this file is, or was ever, a real
credential. They are built to be *recognisable* by pattern: a corpus of `password123` would prove nothing, and a
corpus of real-looking keys is exactly what a scanner should catch.

`SECRETS` is a list of `(kind, secret)` pairs; `corpus()` returns them as bytes with a stable order. The boundary
test uses `splits()`, which yields every offset that would actually divide the secret — that is the condition the
product has to survive, because the network decides where a chunk ends and it has no interest in our regex.
"""
from __future__ import annotations

PREFIX = {
    "openai": "sk-proj",
    "anthropic": "sk-ant-api03",
    "aws": "AKIA",
    "github": "ghp",
    "slack": "xoxb",
}


def _make(kind: str, index: int) -> str:
    body = "".join(chr(ord("A") + ((index * 7 + step) % 26)) for step in range(24 + index % 9))
    digest = f"{index:03d}"
    if kind == "openai":
        return f"sk-proj-{body}{digest}"
    if kind == "anthropic":
        return f"sk-ant-api03-{body}{digest}"
    if kind == "aws":
        return "AKIA" + "".join(chr(ord("A") + ((index + step) % 26)) for step in range(16))
    if kind == "github":
        return f"ghp_{body}{digest}"
    if kind == "slack":
        return f"xoxb-{digest}-{body}"
    if kind == "jwt":
        # Real JWTs carry long base64url segments; a three-segment string with a 7-character tail is not a JWT, and
        # building the corpus from one produced a "miss" that was really a malformed fixture.
        return f"eyJ{body}{body[:8]}.eyJ{body[4:]}{digest}.{body}{digest}"
    if kind == "bearer":
        return f"Bearer {body}{digest}ab"
    if kind == "assignment":
        return f'api_key = "{body}{digest}"'
    if kind == "private_key":
        return ("-----BEGIN RSA PRIVATE KEY-----\n" + body * 2 + "\n" + digest + "\n"
                "-----END RSA PRIVATE KEY-----")
    if kind == "email":
        return f"person{index:02d}.{digest}@example-customer.test"
    raise AssertionError(kind)


KINDS = ("anthropic", "openai", "aws", "github", "slack", "jwt", "bearer", "assignment", "private_key", "email")

SECRETS: list[tuple[str, str]] = [(kind, _make(kind, index)) for index in range(6) for kind in KINDS]


def corpus() -> list[bytes]:
    return [secret.encode() for _kind, secret in SECRETS]


def splits(secret: bytes) -> list[int]:
    """Every offset that divides the secret, so a test can split there and nowhere else."""
    return list(range(1, len(secret)))


def leaked(secret: bytes, haystack: bytes, *, edge: int = 8) -> bool:
    """Did any recognisable piece of `secret` survive? The whole thing, its head, or its tail.

    A redactor that shipped `sk-proj-AAA` and redacted the rest would pass a naive `secret in haystack` check and
    still hand an attacker most of a key. Edge fragments are the conservative test: 8 bytes of an `sk-` key is
    already distinguishing.
    """
    if secret in haystack:
        return True
    if len(secret) < edge * 2:
        return False
    return secret[:edge] in haystack or secret[-edge:] in haystack
